import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { SETTING_DEFINITIONS } from "../src/domain/catalog/settingsSchema.mjs";
import { IPC_TARGETS, SHELL_CONFIG_NAME } from "../src/domain/catalog/ipcCatalog.mjs";
import { DARK_BASE, RADIUS, SPACING, FONT_SIZE, ICON_SIZE, CONTROL_SIZE } from "../src/domain/catalog/tokens.mjs";
import { renderHyprlandConf, renderHyprlandLua, renderHyprlandLuaBinds, renderHyprchords, renderKeybindsMarkdown, renderLayerRulesConf, renderLayerRulesLua } from "./keybindExamples.mjs";

const ROOT = new URL("..", import.meta.url).pathname;
const CHECK_FLAG = "--check";
const MARKDOWN_HEADER = "<!-- Generated by tools/generate.mjs from src/domain/catalog. Do not edit by hand. -->\n\n";
const TABLE_SEPARATOR = " | ";
const EXTRA_COLOR_KEYS = ["accent", "accentHover", "accentPressed", "accentDisabled", "accentText", "textOnAccent", "taskbarBackgroundOpaque", "flyoutBackgroundOpaque"];

/** @param {unknown} value @returns {string} */
function formatDefault(value) {
    return Array.isArray(value) ? value.map((item) => `\`${item}\``).join(", ") || "(empty)" : `\`${JSON.stringify(value)}\``;
}

/** @param {import("../src/domain/settings/definitions.mjs").SettingDefinition} definition @returns {string} */
function formatAllowed(definition) {
    if (definition.options) {
        return definition.options.map((option) => `\`${option}\``).join(", ");
    }
    if (definition.minimum !== undefined && definition.maximum !== undefined) {
        return `${definition.minimum} to ${definition.maximum}`;
    }
    return definition.pattern ? `\`${definition.pattern.source}\`` : "";
}

function renderConfiguration() {
    const sections = [...new Set(SETTING_DEFINITIONS.map((definition) => definition.section))];
    const body = sections.map((section) => {
        const rows = SETTING_DEFINITIONS.filter((definition) => definition.section === section).map((definition) =>
            `| ${[`\`${definition.key}\``, definition.type, formatDefault(definition.defaultValue), formatAllowed(definition), definition.description].join(TABLE_SEPARATOR)} |`);
        return `## ${section}\n\n| Key | Type | Default | Allowed | Description |\n|---|---|---|---|---|\n${rows.join("\n")}\n`;
    }).join("\n");
    const example = JSON.stringify({ schemaVersion: 1, values: { theme: { mode: "light" }, taskbar: { alignment: "left" } } }, null, 4);
    return `${MARKDOWN_HEADER}# Configuration\n\nFile: \`$XDG_CONFIG_HOME/${SHELL_CONFIG_NAME}/settings.json\`. Only keys you change are stored; everything else follows the defaults below. Nested keys are written as nested objects:\n\n\`\`\`json\n${example}\n\`\`\`\n\nInvalid values are ignored, logged as \`settings.invalid\` and shown in Settings. The file is watched and changes apply live.\n\n${body}`;
}

/**
 * @param {Readonly<Record<string, number>>} tokens
 * @returns {string}
 */
function renderMetrics(tokens) {
    const lines = Object.keys(tokens).map((key) => `    readonly property real ${key}: values.${key} * scale`);
    return `import QtQuick\n\nQtObject {\n    required property real scale\n    required property var values\n\n${lines.join("\n")}\n}\n`;
}

function renderColors() {
    const keys = [...Object.keys(DARK_BASE), ...EXTRA_COLOR_KEYS];
    const lines = keys.map((key) => `    property color ${key}: palette.${key}\n    Behavior on ${key} { ColorAnimation { duration: root.duration } }`);
    return `import QtQuick\n\nQtObject {\n    id: root\n\n    required property var palette\n    required property int duration\n\n${lines.join("\n")}\n    readonly property color transparent: "transparent"\n}\n`;
}

/** @type {{ path: string, render: () => string }[]} */
const generatedFiles = [
    { path: "docs/configuration.md", render: renderConfiguration },
    { path: "docs/keybinds.md", render: () => renderKeybindsMarkdown(IPC_TARGETS) },
    { path: "examples/hyprland/keybinds.conf", render: () => renderHyprlandConf(IPC_TARGETS) },
    { path: "examples/hyprland/keybinds.lua", render: () => renderHyprlandLua(IPC_TARGETS) },
    { path: "examples/hyprland/hyprchords.conf", render: () => renderHyprchords(IPC_TARGETS) },
    { path: "examples/hyprland/binds.lua", render: () => renderHyprlandLuaBinds(IPC_TARGETS) },
    { path: "examples/hyprland/layerrules.lua", render: renderLayerRulesLua },
    { path: "examples/hyprland/layerrules.conf", render: renderLayerRulesConf },
    { path: "src/ui/theme/ThemeColors.qml", render: renderColors },
    { path: "src/ui/theme/ThemeSpacingMetrics.qml", render: () => renderMetrics(SPACING) },
    { path: "src/ui/theme/ThemeRadiusMetrics.qml", render: () => renderMetrics(RADIUS) },
    { path: "src/ui/theme/ThemeFontSizeMetrics.qml", render: () => renderMetrics(FONT_SIZE) },
    { path: "src/ui/theme/ThemeIconSizeMetrics.qml", render: () => renderMetrics(ICON_SIZE) },
    { path: "src/ui/theme/ThemeSizeMetrics.qml", render: () => renderMetrics(CONTROL_SIZE) },
];

const checkOnly = process.argv.includes(CHECK_FLAG);
/** @type {string[]} */
const stale = [];
for (const file of generatedFiles) {
    const target = join(ROOT, file.path);
    const content = file.render();
    const current = existsSync(target) ? readFileSync(target, "utf8") : "";
    if (current === content) {
        continue;
    }
    if (checkOnly) {
        stale.push(file.path);
        continue;
    }
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
    console.info(`generated ${file.path}`);
}
if (stale.length > 0) {
    console.error(`Generated files are out of date, run "npm run gen": ${stale.join(", ")}`);
    process.exit(1);
}
